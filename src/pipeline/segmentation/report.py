import calendar
import pandas as pd
import seg_config as cfg
from common import load, read_json
MONTHS = list(calendar.month_abbr)

def md_table(headers, rows) -> str:
    lines = ["| " + " | ".join(headers) + " |", "|" + "---|" * len(headers)]
    lines += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(lines)


def name(c, ch) -> str:
    parts = [f"{'high' if z > 0 else 'low'} {v}" for v, z in ch["top_vars"] if abs(z) >= 0.5][:2]
    return f"C{c}: " + (", ".join(parts) if parts else "near-average conditions")


def months_text(ch) -> str:
    return ", ".join(f"{MONTHS[int(m)]} ({s:.0%})" for m, s in ch["top_months"].items())


def grade_sil(s) -> str:
    return "Strong" if s >= 0.50 else "Moderate" if s >= cfg.COND_SIL else "Weak"


def readiness(val) -> str:
    s, a, n = val["silhouette"], val["ari_mean"], val["neg_silhouette_share"]
    if s >= cfg.READY_SIL and a >= cfg.READY_ARI and n <= cfg.READY_NEG:
        return "READY FOR ADVANCED ANALYTICS"
    if s >= cfg.COND_SIL and a >= cfg.COND_ARI:
        return "CONDITIONALLY READY"
    return "ADDITIONAL DATA REQUIRED"


def section_header(meta, k) -> str:
    return "\n".join([
        "# Intelligent Segmentation", "",
        f"Unit of analysis: municipio-month | municipalities: {meta['municipios']} | period: {meta['period'][0]} to {meta['period'][1]} | "
        f"observations: {meta['n_obs']:,} | final K: {k}", "",
        "Scope: daily environmental variables of the 11 municipalities of Aguascalientes aggregated by month. "
        "All AOD columns, lags, rolling means, targets, static and cyclone columns are excluded. "
        "Segments describe environmental regimes only; they are not forecasts or official assessments. "
        "All outputs are generated by `run_all.py`."])


def section_step2(meta) -> str:
    n_pc, cum = meta["n_pc"], meta["cumulative"][-1]
    agg = [(v, "sum" if v in meta["sum_vars"] else "mean") for v in meta["vars"]]
    pcs = [(f"PC{i + 1}", f"{e:.1%}", f"{c:.1%}", f"{ev:.2f}")
           for i, (e, c, ev) in enumerate(zip(meta["explained"], meta["cumulative"], meta["eigenvalues"]))]
    return "\n".join([
        "## Phase 1 – Clustering Dataset Preparation", "", "### Step 2 – Clustering Dataset Preparation", "",
        "#### Clustering Dataset Report", "",
        md_table(["Dataset", "Observations", "Variables"], [
            ("Master table (daily, municipio-day)", f"{meta['n_rows_master']:,}", meta["n_cols_master"]),
            ("Monthly aggregation (municipio-month)", f"{meta['n_obs']:,}", meta["n_vars"]),
            ("Clustering Dataset (PCA scores)", f"{meta['n_obs']:,}", n_pc)]), "",
        f"Months with fewer than {meta['min_days']} observed days were dropped ({meta['n_months_dropped']} municipio-months).", "",
        "#### Segmentation Input Structure Report", "",
        md_table(["Input Type", "Variables / Components", "Justification"], [
            ("Original Variables", ", ".join(f"`{v}` ({a})" for v, a in agg),
             "Raw daily weather variables, aggregated by month (rainfall summed, the rest averaged). Derived features, targets, "
             "static/cyclone columns and every AOD column are excluded: AOD showed no useful signal and has a 79.4 % coverage."),
            ("PCA Components", f"PC1–PC{n_pc}",
             f"Retain ≥ {meta['pca_var']:.0%} of the variance ({cum:.1%} with {n_pc} components); Kaiser criterion (eigenvalue > 1) keeps {meta['kaiser']}. "
             "PCA removes the strong collinearity between temperature, humidity and radiation so K-Means distances are not dominated by one physical driver.")]), "",
        "**Scaling strategy:** z-score standardization (`StandardScaler`) of every variable before PCA, so units (°C, mm, kPa) do not weight the distance.", "",
        "**PCA usage:** a single PCA fitted on the whole municipio-month matrix. The walk-forward PCA of `src/data_analysis/pca_walkforward.py` "
        "is fitted per fold to avoid leakage in forecasting; segmentation is descriptive, so one global fit is appropriate here.", "",
        md_table(["Component", "Explained variance", "Cumulative variance", "Eigenvalue"], pcs), "",
        "![PCA scree plot](pca_scree.png)", "", "Loadings of every variable on every component: `pca_loadings.csv`."])


def section_step3(km, configs, assign) -> str:
    rows = [(r.k, f"{r.inertia:,.1f}", f"{r.silhouette:.3f}", r.interpretation) for r in configs.itertuples()]
    return "\n".join([
        "## Phase 2 – Cluster Generation", "", "### Step 3 – K-Means Clustering", "",
        f"Candidate values of K: {configs['k'].min()}–{configs['k'].max()} (`n_init=10`, `random_state={cfg.SEED}`, run on the PCA scores). "
        f"Elbow suggests K={km['k_elbow']}; the best silhouette with K ≥ {cfg.K_FINAL_MIN} is K={km['k_best_silhouette']}. "
        f"**Final K = {km['k_final']}.** Rule: highest silhouette among K ≥ {cfg.K_FINAL_MIN}, because K=2 normally only splits the year into two seasons "
        "and carries little domain information.", "", "#### K-Means Configuration Matrix", "",
        md_table(["K", "Inertia", "Silhouette Score", "Interpretation"], rows), "",
        "![Elbow and silhouette](kmeans_selection.png)", "", "#### Cluster Assignment Report", "",
        md_table(["Cluster", "Number of Observations", "Share"], [(f"C{r.cluster}", r.n, f"{r.share:.1%}") for r in assign.itertuples()])])


def section_step4(d, meta, val, chars, k) -> str:
    cen = d.groupby("cluster")["PC1"].mean()
    pc_eta = val["pc_eta2"]
    pcs = ", ".join(f"{p} {v:.2f}" for p, v in list(pc_eta.items())[:3])
    sizes = d["cluster"].value_counts()
    items = [
        ("PCA scatter plot", "pca_scatter.png",
         "Every municipio-month projected on PC1/PC2 and colored by cluster; X marks the centroids.",
         f"PC1+PC2 retain {sum(meta['explained'][:2]):.0%} of the variance; centroids span PC1 from {cen.min():.1f} to {cen.max():.1f}; "
         f"overall silhouette {val['silhouette']:.2f}.",
         "Shows whether segments are separated in the space where K-Means actually ran."),
        ("Cluster centroid visualization", "centroid_heatmap.png",
         "Mean z-score of each original variable per cluster.",
         "; ".join(name(c, ch) for c, ch in chars.items()) + ".",
         "Translates the abstract components back into physical variables a reader can interpret."),
        ("Pair plot", "pair_plot.png",
         "Pairwise scatter and histograms of the first three components by cluster.",
         f"Variance of each component explained by the clusters (η²): {pcs}. Low values mean the components overlap across clusters.",
         "Reveals which components carry the separation and where clusters overlap."),
        ("Cluster distribution", "cluster_sizes.png",
         "Number of observations per cluster.",
         f"Largest cluster {sizes.max()} observations ({sizes.max() / len(d):.0%}); smallest {sizes.min()} ({sizes.min() / len(d):.0%}).",
         "Very unbalanced clusters indicate rare regimes or an over-split solution."),
        ("Calendar-month distribution", "cluster_by_month.png",
         "Share of each cluster's observations falling in each calendar month.",
         f"NMI(cluster, month) = {val['nmi_month']:.2f}. " + "; ".join(f"C{c}: {months_text(ch)}" for c, ch in chars.items()) + ".",
         "Quantifies how much of the segmentation is just seasonality."),
        ("Municipality composition", "cluster_by_municipio.png",
         "Share of each municipality's months that fall in each cluster.",
         f"NMI(cluster, municipio) = {val['nmi_municipio']:.2f}; a municipality visits {val['avg_clusters_per_municipio']:.1f} of {k} clusters on average.",
         "Shows whether segments describe places or regimes shared by all municipalities."),
    ]
    out = ["### Step 4 – Cluster Visualization", "", "#### Cluster Visualization Dashboard", ""]
    for title, img, what, pattern, why in items:
        out += [f"**{title}**", "", f"![{title}]({img})", "", f"- **What is visualized:** {what}", f"- **Patterns:** {pattern}", f"- **Why it matters:** {why}", ""]
    return "\n".join(out)


def section_step5(chars, profile, zprofile, eta) -> str:
    rows = []
    for c, ch in chars.items():
        main = "; ".join(f"{'high' if z > 0 else 'low'} `{v}` (z={z:+.2f}, mean {profile.loc[c, v]:.1f})" for v, z in ch["top_vars"])
        meaning = (f"{ch['n']} months ({ch['share']:.0%}); most frequent in {months_text(ch)}; present in {ch['n_municipios']} of 11 municipalities "
                   f"(largest municipality share {ch['max_muni_share']:.0%}).")
        rows.append((f"C{c}", main, meaning))
    prof = [(f"C{c}", *(f"{v:.2f}" for v in r)) for c, r in profile.iterrows()]
    return "\n".join([
        "## Phase 3 – Cluster Interpretation", "", "### Step 5 – Segment Characterization", "",
        "#### Cluster Characterization Matrix", "",
        md_table(["Cluster", "Main Characteristics", "Interpretation"], rows), "",
        "**Mean of each variable by cluster (original units)**", "", md_table(["Cluster"] + list(profile.columns), prof), "",
        "**Distinguishing variables** (η² = share of the variable's variance explained by the clusters)", "",
        md_table(["Variable", "η²"], [(f"`{v}`", f"{e:.2f}") for v, e in eta.items()])])


def section_step6(val, chars, k) -> str:
    s, a, neg = val["silhouette"], val["ari_mean"], val["neg_silhouette_share"]
    worst = min(val["silhouette_per_cluster"].items(), key=lambda kv: kv[1])
    cons = "Stable" if a >= cfg.READY_ARI and neg <= cfg.READY_NEG else "Acceptable" if a >= cfg.COND_ARI else "Unstable"
    practical = "Useful" if val["min_share"] >= 0.05 and k <= 6 else "Limited"
    rows = [
        ("Separation", grade_sil(s), f"Silhouette {s:.2f}; Davies-Bouldin {val['davies_bouldin']:.2f} (lower is better); "
                                    f"Calinski-Harabasz {val['calinski_harabasz']:.0f}; PC1 η² {val['pc_eta2']['PC1']:.2f}"),
        ("Consistency", cons, f"{neg:.1%} of observations have negative silhouette; weakest cluster C{worst[0]} ({worst[1]:.2f}); "
                              f"bootstrap ARI {a:.2f} ± {val['ari_std']:.2f} ({cfg.BOOT_RUNS} fits on 80 % subsamples)"),
        ("Practical Value", practical, f"{k} segments, smallest holds {val['min_share']:.0%} of observations; "
                                       f"NMI with calendar month {val['nmi_month']:.2f}, with municipality {val['nmi_municipio']:.2f}"),
    ]
    per = [(f"C{c}", f"{v:.2f}") for c, v in val["silhouette_per_cluster"].items()]
    return "\n".join(["### Step 6 – Segmentation Validation", "", "#### Segmentation Validation Matrix", "",
                      md_table(["Criterion", "Assessment", "Evidence"], rows), "",
                      "Silhouette reading: ≥ 0.50 strong, 0.25–0.50 moderate (weak structure), < 0.25 weak.", "",
                      "**Mean silhouette per cluster**", "", md_table(["Cluster", "Silhouette"], per)])


def insight_rows(val, chars, eta, k):
    nm, nu = val["nmi_month"], val["nmi_municipio"]
    small_c = min(chars, key=lambda c: chars[c]["n"])
    small = chars[small_c]
    top = eta.head(3)
    return [
        ("Segments follow the calendar" if nm >= 0.5 else "Segments only partly follow the calendar",
         f"NMI(cluster, month) = {nm:.2f}",
         "Most of the structure is seasonal; segments add value mainly where they split a season into distinct regimes." if nm >= 0.5
         else "Segments contain information beyond the time of year."),
        ("Segments are regimes, not places" if nu < 0.15 else "Segments partly separate municipalities",
         f"NMI(cluster, municipio) = {nu:.2f}; each municipality visits {val['avg_clusters_per_municipio']:.1f} of {k} clusters",
         "Municipalities share the same weather regimes, so one regional segmentation is enough." if nu < 0.15
         else "Municipal differences matter; segment-specific monitoring may be justified."),
        ("Few variables drive the segmentation", "Top η²: " + ", ".join(f"`{v}` {e:.2f}" for v, e in top.items()),
         "Monitoring and any future feature selection can start from these variables."),
        (f"Smallest segment (C{small_c}) is a rare regime", f"{small['n']} months ({small['share']:.1%}); {name(small_c, small)}",
         "Candidate for an atypical-month watch; interpret with care because of its size."),
    ]


def section_step7(val, chars, eta, k) -> str:
    return "\n".join([
        "## Phase 4 – Segment Intelligence", "", "### Step 7 – Segment Insights", "",
        "**Emerging profiles:** " + " | ".join(name(c, ch) for c, ch in chars.items()), "",
        f"**Hidden structures:** clusters explain {val['pc_eta2']['PC1']:.0%} of PC1 variance; see the insights below for what segmentation adds beyond season and place.", "",
        "**Project value:** the segment label can be (a) a categorical feature for the rain-occurrence and T2M_MIN models, "
        "(b) a stratifier to check whether model skill differs by regime, (c) a context flag for the rolling-skill monitoring.", "",
        "#### Segmentation Insights Matrix", "", md_table(["Insight", "Evidence", "Practical Meaning"], insight_rows(val, chars, eta, k))])


def section_step8(val, chars, k, verdict) -> str:
    s, a = val["silhouette"], val["ari_mean"]
    rows = [
        ("Segmentation Quality", grade_sil(s), f"Silhouette {s:.2f}, ARI {a:.2f}, negative-silhouette share {val['neg_silhouette_share']:.1%}"),
        ("Analytical Value", "Useful" if val["nmi_month"] < 0.9 else "Limited",
         f"NMI with month {val['nmi_month']:.2f}: {'segments add information beyond season' if val['nmi_month'] < 0.9 else 'segments are almost a calendar split'}"),
        ("Practical Utility", "Supports descriptive regime analysis and model stratification",
         f"{k} segments, smallest {val['min_share']:.0%} of observations; no predictive claim is made"),
    ]
    return "\n".join([
        "### Step 8 – Intelligent Segmentation Assessment", "", "#### Intelligent Segmentation Assessment and Analytical Roadmap", "",
        md_table(["Dimension", "Assessment", "Evidence"], rows), "",
        f"Criteria: READY = silhouette ≥ {cfg.READY_SIL}, ARI ≥ {cfg.READY_ARI}, negative silhouette ≤ {cfg.READY_NEG:.0%}; "
        f"CONDITIONALLY READY = silhouette ≥ {cfg.COND_SIL} and ARI ≥ {cfg.COND_ARI}; otherwise ADDITIONAL DATA REQUIRED.", "",
        f"**Classification of the project: {verdict}**", "", "#### Future Analytical Directions", "",
        md_table(["Direction", "Why"], [
            ("Model Performance Validation", "Compare walk-forward skill of the rain and T2M_MIN models inside each segment."),
            ("Explainable AI Workshop", "Use segment label vs. feature importance to explain when the models work."),
            ("Predictive Intelligence Engine", "Add the segment as a feature and as a monitoring dimension."),
            ("Deep Learning Innovation Lab", "Not justified by this segmentation alone.")])])


def section_summary(meta, val, chars, eta, k, verdict) -> str:
    ins = insight_rows(val, chars, eta, k)
    return "\n".join([
        "## Executive Summary", "",
        f"- **Number of clusters:** {k} (K-Means on {meta['n_pc']} PCA components, {meta['cumulative'][-1]:.0%} variance, {meta['n_obs']:,} municipio-months).",
        "- **Main segment characteristics:** " + " | ".join(name(c, ch) for c, ch in chars.items()) + ".",
        f"- **Most relevant insights:** {ins[0][0]} ({ins[0][1]}); {ins[1][0].lower()} ({ins[1][1]}).",
        "- **Limitations:** only 11 municipalities sharing weather systems; ~monthly aggregation hides within-month variability; "
        "K-Means assumes compact, similar-size clusters; AOD excluded; no external validation of the segments.",
        f"- **Readiness assessment:** **{verdict}**."])


def main():
    meta, km, val = read_json("prep_meta.json"), read_json("kmeans_meta.json"), read_json("validation.json")
    chars = {int(c): v for c, v in read_json("characterization.json").items()}
    configs = pd.read_csv(cfg.OUT / "kmeans_configs.csv").fillna("-")
    assign = pd.read_csv(cfg.OUT / "cluster_assignment.csv")
    profile = pd.read_csv(cfg.OUT / "profile.csv", index_col=0)
    zprofile = pd.read_csv(cfg.OUT / "profile_z.csv", index_col=0)
    eta = pd.read_csv(cfg.OUT / "eta2.csv", index_col=0)["eta2"]
    d, k, verdict = load(), km["k_final"], readiness(val)
    d["cal_month"] = d["month"].dt.month

    sections = [section_header(meta, k), section_step2(meta), section_step3(km, configs, assign),
                section_step4(d, meta, val, chars, k), section_step5(chars, profile, zprofile, eta),
                section_step6(val, chars, k), section_step7(val, chars, eta, k),
                section_step8(val, chars, k, verdict), section_summary(meta, val, chars, eta, k, verdict)]
    path = cfg.OUT / "intelligent_segmentation.md"
    path.write_text("\n\n".join(sections) + "\n", encoding="utf-8")
    return path


if __name__ == "__main__":
    print(main())